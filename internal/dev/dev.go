// Package dev holds what lodo dev needs to start a project's Node apps on the
// project's address: the package manager that runs the dev script, the
// address each of the project's ports binds, and the listen hook Node loads
// through NODE_OPTIONS.
package dev

import (
	_ "embed" // for bindJS
	"encoding/json"
	"errors"
	"fmt"
	"io/fs"
	"maps"
	"os"
	"path/filepath"
	"slices"
	"strings"

	"github.com/sangdth/lodo/internal/fsutil"
	"github.com/sangdth/lodo/internal/paths"
	"github.com/sangdth/lodo/internal/store"
)

// bindJS is the listen hook: it wraps net.Server's listen so a listen on a
// listed port binds that port's address.
//
//go:embed bind.cjs
var bindJS []byte

// managers are the package managers lodo dev runs, by command name.
var managers = []string{"pnpm", "yarn", "bun", "npm"}

// lockFiles name the package manager of each lock file, in the order
// PackageManager looks for them.
var lockFiles = []struct{ file, manager string }{
	{"pnpm-lock.yaml", "pnpm"},
	{"yarn.lock", "yarn"},
	{"bun.lock", "bun"},
	{"bun.lockb", "bun"},
	{"package-lock.json", "npm"},
}

// PackageManager returns the command that runs root's dev script: pnpm, yarn,
// bun or npm. The packageManager field of root's package.json wins, then a
// lock file in root, then npm. It refuses a root without a package.json or a
// dev script.
func PackageManager(root string) (string, error) {
	path := filepath.Join(root, "package.json")
	data, err := fsutil.ReadRegular(path)
	if errors.Is(err, fs.ErrNotExist) {
		return "", fmt.Errorf("%s has no package.json", root)
	}
	if err != nil {
		return "", err
	}
	var pkg struct {
		PackageManager string            `json:"packageManager"`
		Scripts        map[string]string `json:"scripts"`
	}
	if err := json.Unmarshal(data, &pkg); err != nil {
		return "", fmt.Errorf("read %s: %w", path, err)
	}
	if _, ok := pkg.Scripts["dev"]; !ok {
		if len(pkg.Scripts) == 0 {
			return "", fmt.Errorf("%s has no dev script and no other scripts", path)
		}
		return "", fmt.Errorf("%s has no dev script, only %s", path, strings.Join(slices.Sorted(maps.Keys(pkg.Scripts)), ", "))
	}
	if pkg.PackageManager != "" {
		// pnpm@9.1.0, or yarn@4.1.0+sha512.<hash>
		name, _, _ := strings.Cut(pkg.PackageManager, "@")
		if !slices.Contains(managers, name) {
			return "", fmt.Errorf("%s: packageManager %q is none of %s", path, pkg.PackageManager, strings.Join(managers, ", "))
		}
		return name, nil
	}
	for _, l := range lockFiles {
		if _, err := os.Stat(filepath.Join(root, l.file)); err == nil {
			return l.manager, nil
		}
	}
	return "npm", nil
}

// Ports returns the address each port of project binds: the ports of
// project's own name and the names under it that are on. Two of them on one
// port with different addresses are an error, since the hook sees only the
// port.
func Ports(domains []store.Domain, project string) (map[int]string, error) {
	names := store.Under(domains, project)
	if d, ok := store.Find(domains, project); ok {
		names = append([]store.Domain{d}, names...)
	}
	ports := map[int]string{}
	owners := map[int]string{} // the first name on each port, for the error
	for _, d := range names {
		if !d.HasSite() {
			continue
		}
		if addr, ok := ports[d.Port]; ok && addr != d.Address {
			return nil, fmt.Errorf("%s (%s) and %s (%s) both use port %d: lodo dev binds one app per port: give one of them another port",
				owners[d.Port], addr, d.Name, d.Address, d.Port)
		}
		ports[d.Port], owners[d.Port] = d.Address, d.Name
	}
	return ports, nil
}

// Hook returns project's hook file: it calls the listen hook at bindPath
// with ports and ".<project>", the Vite host that allows project's names.
func Hook(bindPath, project string, ports map[int]string) []byte {
	path, _ := json.Marshal(bindPath)       // a string always marshals; JSON is a JS literal
	hosts, _ := json.Marshal("." + project) // so does this one
	m, _ := json.Marshal(ports)             // map keys come out sorted
	return fmt.Appendf(nil, "// Generated by lodo dev from domains.json. Edits are overwritten.\nrequire(%s)(%s, %s);\n",
		path, m, hosts)
}

// NodeOptions returns existing, a NODE_OPTIONS value, with a --require of
// hookPath after it, quoted and escaped the way Node splits NODE_OPTIONS. When
// existing already holds that --require it comes back unchanged.
func NodeOptions(existing, hookPath string) string {
	req := `--require "` + strings.NewReplacer(`\`, `\\`, `"`, `\"`).Replace(hookPath) + `"`
	switch {
	case existing == "":
		return req
	case strings.Contains(existing, req):
		return existing
	}
	return existing + " " + req
}

// WriteHooks writes the listen hook to p.BindHook and project's hook file,
// which passes it ports and ".<project>", into p.DevDir. It returns the hook file's path, for
// NodeOptions.
func WriteHooks(p paths.Paths, project string, ports map[int]string) (string, error) {
	// The name becomes a file name.
	if err := store.ValidateProject(project); err != nil {
		return "", fmt.Errorf("project %q: %w", project, err)
	}
	if err := os.MkdirAll(p.DevDir, 0o755); err != nil { //nolint:gosec // G301: the hooks hold no secrets
		return "", fmt.Errorf("create %s: %w", p.DevDir, err)
	}
	if _, err := fsutil.WriteFile(p.BindHook, bindJS, 0o644); err != nil {
		return "", err
	}
	hook := filepath.Join(p.DevDir, project+".cjs")
	if _, err := fsutil.WriteFile(hook, Hook(p.BindHook, project, ports), 0o644); err != nil {
		return "", err
	}
	return hook, nil
}
